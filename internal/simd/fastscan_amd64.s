#include "textflag.h"

// func fastScanAVX2(nibs *byte, lut *byte, pairs, blocks int, out *uint16)
TEXT ·fastScanAVX2(SB), NOSPLIT, $0-40
	MOVQ nibs+0(FP), SI
	MOVQ lut+8(FP), DX
	MOVQ pairs+16(FP), CX
	MOVQ blocks+24(FP), R8
	MOVQ out+32(FP), DI
	MOVQ $0x0f0f0f0f0f0f0f0f, AX
	MOVQ AX, X15
	VPBROADCASTQ X15, Y15 // 0x0F per byte
	VPCMPEQW Y14, Y14, Y14
	VPSRLW $8, Y14, Y14   // 0x00FF per word

block:
	VPXOR Y0, Y0, Y0 // low nibbles, even bytes: rows 0, 2, ... 14
	VPXOR Y1, Y1, Y1 // low nibbles, odd bytes: rows 1, 3, ... 15
	VPXOR Y2, Y2, Y2 // high nibbles, even bytes: rows 16, 18, ... 30
	VPXOR Y3, Y3, Y3 // high nibbles, odd bytes: rows 17, 19, ... 31
	MOVQ DX, BX
	MOVQ CX, R9

pair:
	VMOVDQU (SI), Y4
	VMOVDQU (BX), Y5
	VPAND Y15, Y4, Y6
	VPSRLW $4, Y4, Y7
	VPAND Y15, Y7, Y7
	VPSHUFB Y6, Y5, Y6
	VPSHUFB Y7, Y5, Y7
	VPAND Y14, Y6, Y8
	VPADDW Y8, Y0, Y0
	VPSRLW $8, Y6, Y6
	VPADDW Y6, Y1, Y1
	VPAND Y14, Y7, Y8
	VPADDW Y8, Y2, Y2
	VPSRLW $8, Y7, Y7
	VPADDW Y7, Y3, Y3
	ADDQ $32, SI
	ADDQ $32, BX
	DECQ R9
	JNZ  pair

	// Fold the two groups' lanes, then interleave even and odd rows.
	VEXTRACTI128 $1, Y0, X8
	VPADDW X8, X0, X0
	VEXTRACTI128 $1, Y1, X8
	VPADDW X8, X1, X1
	VEXTRACTI128 $1, Y2, X8
	VPADDW X8, X2, X2
	VEXTRACTI128 $1, Y3, X8
	VPADDW X8, X3, X3
	VPUNPCKLWD X1, X0, X8
	VMOVDQU X8, (DI)
	VPUNPCKHWD X1, X0, X8
	VMOVDQU X8, 16(DI)
	VPUNPCKLWD X3, X2, X8
	VMOVDQU X8, 32(DI)
	VPUNPCKHWD X3, X2, X8
	VMOVDQU X8, 48(DI)
	ADDQ $64, DI
	DECQ R8
	JNZ  block

	VZEROUPPER
	RET

// func fastScan2AVX2(nibs, lutA, lutB *byte, pairs, blocks int, outA, outB *uint16)
TEXT ·fastScan2AVX2(SB), NOSPLIT, $0-56
	MOVQ nibs+0(FP), SI
	MOVQ lutA+8(FP), DX
	MOVQ lutB+16(FP), R12
	MOVQ pairs+24(FP), CX
	MOVQ blocks+32(FP), R8
	MOVQ outA+40(FP), DI
	MOVQ outB+48(FP), R13
	MOVQ $0x0f0f0f0f0f0f0f0f, AX
	MOVQ AX, X15
	VPBROADCASTQ X15, Y15
	VPCMPEQW Y14, Y14, Y14
	VPSRLW $8, Y14, Y14

block2:
	VPXOR Y0, Y0, Y0
	VPXOR Y1, Y1, Y1
	VPXOR Y2, Y2, Y2
	VPXOR Y3, Y3, Y3
	VPXOR Y8, Y8, Y8
	VPXOR Y9, Y9, Y9
	VPXOR Y10, Y10, Y10
	VPXOR Y11, Y11, Y11
	MOVQ DX, BX
	MOVQ R12, R11
	MOVQ CX, R9

pair2:
	VMOVDQU (SI), Y4
	VPAND Y15, Y4, Y6
	VPSRLW $4, Y4, Y7
	VPAND Y15, Y7, Y7
	VMOVDQU (BX), Y5
	VPSHUFB Y6, Y5, Y12
	VPSHUFB Y7, Y5, Y13
	VPAND Y14, Y12, Y5
	VPADDW Y5, Y0, Y0
	VPSRLW $8, Y12, Y12
	VPADDW Y12, Y1, Y1
	VPAND Y14, Y13, Y5
	VPADDW Y5, Y2, Y2
	VPSRLW $8, Y13, Y13
	VPADDW Y13, Y3, Y3
	VMOVDQU (R11), Y5
	VPSHUFB Y6, Y5, Y12
	VPSHUFB Y7, Y5, Y13
	VPAND Y14, Y12, Y5
	VPADDW Y5, Y8, Y8
	VPSRLW $8, Y12, Y12
	VPADDW Y12, Y9, Y9
	VPAND Y14, Y13, Y5
	VPADDW Y5, Y10, Y10
	VPSRLW $8, Y13, Y13
	VPADDW Y13, Y11, Y11
	ADDQ $32, SI
	ADDQ $32, BX
	ADDQ $32, R11
	DECQ R9
	JNZ  pair2

	VEXTRACTI128 $1, Y0, X4
	VPADDW X4, X0, X0
	VEXTRACTI128 $1, Y1, X4
	VPADDW X4, X1, X1
	VEXTRACTI128 $1, Y2, X4
	VPADDW X4, X2, X2
	VEXTRACTI128 $1, Y3, X4
	VPADDW X4, X3, X3
	VPUNPCKLWD X1, X0, X4
	VMOVDQU X4, (DI)
	VPUNPCKHWD X1, X0, X4
	VMOVDQU X4, 16(DI)
	VPUNPCKLWD X3, X2, X4
	VMOVDQU X4, 32(DI)
	VPUNPCKHWD X3, X2, X4
	VMOVDQU X4, 48(DI)
	VEXTRACTI128 $1, Y8, X4
	VPADDW X4, X8, X8
	VEXTRACTI128 $1, Y9, X4
	VPADDW X4, X9, X9
	VEXTRACTI128 $1, Y10, X4
	VPADDW X4, X10, X10
	VEXTRACTI128 $1, Y11, X4
	VPADDW X4, X11, X11
	VPUNPCKLWD X9, X8, X4
	VMOVDQU X4, (R13)
	VPUNPCKHWD X9, X8, X4
	VMOVDQU X4, 16(R13)
	VPUNPCKLWD X11, X10, X4
	VMOVDQU X4, 32(R13)
	VPUNPCKHWD X11, X10, X4
	VMOVDQU X4, 48(R13)
	ADDQ $64, DI
	ADDQ $64, R13
	DECQ R8
	JNZ  block2

	VZEROUPPER
	RET
